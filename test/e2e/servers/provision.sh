#!/usr/bin/env bash
# Provision a headless test server directory from the templates.
#
#   provision.sh NAME --flavor paper|folia|canvas [--port 25601] [--profile baseline|pandaeye|hotload]
#                [--no-probe] [--fresh] [--xmx 1536M] [--compression 256]
#                [--pandaeye-jar PATH] [--cloud-endpoint URL] [--license KEY] [--mode shadow|live]
#                [--telemetry-full] [--debug] [--extra-plugin JAR]... [--kbsync-ping PING|KEEPALIVE]
#
# Profiles (plugins copied into plugins/):
#   baseline  PacketEvents b906 (reEncodeByDefault as shipped), ViaVersion, ViaBackwards, PlugManX, KnockbackSync
#   pandaeye  baseline + PandaEye jar + generated plugins/PandaEye/config.yml (shadow mode, local cloud)
#   hotload   baseline + generated PandaEye config; the jar is staged in staged/PandaEye.jar and loaded after
#             start with `plugman load PandaEye` (see hotload.sh)
# The probe plugin (test/e2e/probe-plugin) is added unless --no-probe.
# Re-provisioning an existing dir keeps the world and plugin data folders but replaces jars and configs.
set -euo pipefail
source "$(dirname "$0")/../lib/env.sh"

NAME="${1:-}"; [[ -n "$NAME" && "$NAME" != --* ]] || die "usage: provision.sh NAME --flavor paper|folia|canvas [...]"
shift
FLAVOR=paper PORT=25601 PROFILE=baseline PROBE=1 FRESH=0 XMX="$PE_E2E_XMX" COMPRESSION=256
PE_JAR="" ENDPOINT="$PE_CLOUD_GATEWAY" LICENSE="$PE_E2E_LICENSE" MODE=shadow TELEMETRY_FULL=false DEBUG=false
EXTRA=()
KBSYNC_PING="${PE_E2E_KBSYNC_PING:-PING}"   # production KnockbackSync sends PINGs
while [[ $# -gt 0 ]]; do
  case "$1" in
    --flavor) FLAVOR="$2"; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    --profile) PROFILE="$2"; shift 2 ;;
    --no-probe) PROBE=0; shift ;;
    --fresh) FRESH=1; shift ;;
    --xmx) XMX="$2"; shift 2 ;;
    --compression) COMPRESSION="$2"; shift 2 ;;
    --pandaeye-jar) PE_JAR="$2"; shift 2 ;;
    --cloud-endpoint) ENDPOINT="$2"; shift 2 ;;
    --license) LICENSE="$2"; shift 2 ;;
    --mode) MODE="$2"; shift 2 ;;
    --telemetry-full) TELEMETRY_FULL=true; shift ;;
    --debug) DEBUG=true; shift ;;
    --extra-plugin) EXTRA+=("$2"); shift 2 ;;
    --kbsync-ping) KBSYNC_PING="$2"; shift 2 ;;
    *) die "unknown option $1" ;;
  esac
done

JAR="$(server_jar_for "$FLAVOR")"
[[ -f "$JAR" ]] || die "server jar missing: $JAR"
DIR="$SERVERS_DIR/$NAME"
TPL="$E2E_DIR/servers/templates"

if [[ -f "$DIR/server.pid" ]] && kill -0 "$(cat "$DIR/server.pid")" 2>/dev/null; then
  die "server $NAME is running (pid $(cat "$DIR/server.pid")); stop it first"
fi
[[ $FRESH == 1 ]] && rm -rf "$DIR"
mkdir -p "$DIR/config" "$DIR/plugins" "$DIR/logs" "$DIR/probe" "$CACHE_DIR"

echo "eula=true" > "$DIR/eula.txt"
sed -e "s/@PORT@/$PORT/" -e "s/@NAME@/$NAME/" -e "s/@COMPRESSION@/$COMPRESSION/" "$TPL/server.properties" > "$DIR/server.properties"
cp "$TPL/bukkit.yml" "$TPL/spigot.yml" "$DIR/"
cp "$TPL/config/paper-global.yml" "$TPL/config/paper-world-defaults.yml" "$DIR/config/"
if [[ "$FLAVOR" != paper ]]; then
  grep -v '^#' "$TPL/config/paper-global.folia.yml" >> "$DIR/config/paper-global.yml"
fi

# plugins: replace every jar we manage, keep data folders
find "$DIR/plugins" -maxdepth 1 -name '*.jar' -delete
rm -rf "$DIR/staged"
for j in "$PE_PLUGIN_PACKETEVENTS" "$PE_PLUGIN_VIAVERSION" "$PE_PLUGIN_VIABACKWARDS" "$PE_PLUGIN_PLUGMAN" "$PE_PLUGIN_KBSYNC"; do
  [[ -f "$j" ]] || die "plugin missing: $j"
  cp "$j" "$DIR/plugins/"
done
if [[ $PROBE == 1 ]]; then
  [[ -f "$PE_PROBE_JAR" ]] || die "probe plugin not built: run test/e2e/probe-plugin/build.sh"
  cp "$PE_PROBE_JAR" "$DIR/plugins/PandaEyeProbe.jar"
fi
for j in "${EXTRA[@]}"; do cp "$j" "$DIR/plugins/"; done
# KnockbackSync config (seeded before its first start): no update notifications, ping strategy as in production
mkdir -p "$DIR/plugins/KnockbackSync"
sed -e "s/@KBSYNC_PING_STRATEGY@/$KBSYNC_PING/" "$TPL/plugins/KnockbackSync/config.yml" > "$DIR/plugins/KnockbackSync/config.yml"

write_pandaeye_config() {
  mkdir -p "$DIR/plugins/PandaEye"
  cat > "$DIR/plugins/PandaEye/config.yml" <<EOF
# generated by test/e2e/servers/provision.sh (profile $PROFILE) - ARCHITECTURE.md 4.11 defaults + e2e endpoint
mode: $MODE
server-name: "e2e-$NAME"
network-id: ""
cloud:
  enabled: true
  endpoint: "$ENDPOINT"
  license-key: "$LICENSE"
  batch-interval-ms: 50
  max-buffer-mb: 64
  max-buffer-age-minutes: 10
telemetry:
  full: $TELEMETRY_FULL
  focus-seconds: 5
  idle-sample-hz: 2
checks:
  timer.balance: { enabled: true }
  movement.speed: { enabled: true }
  movement.fly: { enabled: true }
  movement.step: { enabled: true }
  movement.groundspoof: { enabled: true }
  movement.noslow: { enabled: true }
  dig.speed: { enabled: true }
  protocol.pitch: { enabled: true }
  protocol.position: { enabled: true }
  protocol.slot: { enabled: true }
  protocol.selfhit: { enabled: true }
  protocol.cursor: { enabled: true }
  protocol.flood: { enabled: true }
  protocol.abilities: { enabled: true }
  inventory.closed: { enabled: true }
alerts:
  console: true
  in-game-default: auto
  log-file: true
exempt:
  bedrock: true
  bypass-detection-in-shadow: false
proxy:
  session-channel: false
  secret: ""
setbacks:
  enabled: true
punishments:
  kick-command: ""
  kick-message: "Unfair advantage detected"
  ban-command: "ban %player% Unfair advantage. Appeal at %appeal_url% with code %appeal_code%"
  unban-command: "pardon %player%"
  appeal-url: ""
  max-bans-per-hour: 3
  max-kicks-per-10min: 5
mitigations:
  enabled: true
debug: $DEBUG
EOF
}

case "$PROFILE" in
  baseline) ;;
  pandaeye|hotload)
    if [[ -z "$PE_JAR" ]]; then PE_JAR="$(find_pandaeye_jar || true)"; fi
    [[ -n "$PE_JAR" && -f "$PE_JAR" ]] || die "PandaEye jar not found (looked for $PE_PANDAEYE_JAR_GLOB); pass --pandaeye-jar"
    write_pandaeye_config
    if [[ "$PROFILE" == pandaeye ]]; then
      cp "$PE_JAR" "$DIR/plugins/PandaEye.jar"
    else
      mkdir -p "$DIR/staged" && cp "$PE_JAR" "$DIR/staged/PandaEye.jar"
    fi
    ;;
  *) die "unknown profile $PROFILE" ;;
esac

cat > "$DIR/e2e-server.env" <<EOF
NAME=$NAME
FLAVOR=$FLAVOR
PORT=$PORT
PROFILE=$PROFILE
SERVER_JAR=$JAR
XMX=$XMX
CPUS=$PE_E2E_CPUS
PANDAEYE_JAR=${PE_JAR}
EOF
log "provisioned $NAME ($FLAVOR, profile $PROFILE, port $PORT) in $DIR"
echo "$DIR"
