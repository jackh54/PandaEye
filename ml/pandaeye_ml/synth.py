def _player_traits(rng: np.random.Generator, style: str) -> dict[str, float]:
    laggy = style == "laggy"
    ping = float(rng.uniform(130, 320) if laggy else rng.lognormal(np.log(45), 0.5))
    butterfly = rng.random() < 0.15
    return {
        "ping": ping,
        "laggy": float(laggy),
        "cps": float(rng.uniform(12, 19) if butterfly else rng.uniform(5.5, 11.5)),
        "doubles": float(rng.uniform(0.15, 0.4) if butterfly else rng.uniform(0.0, 0.08)),
        "aim_err": float(rng.uniform(2.0, 3.5) if style == "pvp" else rng.uniform(3.0, 9.0)),
        "reach_mu": float(rng.uniform(2.45, 2.8) if style == "pvp" else rng.uniform(2.1, 2.7)),
        "calibrated": float(rng.random() < 0.85),
        "jump_reset": float(rng.uniform(0.2, 0.6) if style == "pvp" else rng.uniform(0.0, 0.15)),
        "yaw_speed": float(rng.uniform(3, 12)),
        "bridge_speed": float(rng.uniform(4.5, 7.5) if style == "builder" else rng.uniform(1.5, 4.5)),
        "mine_speed": float(rng.uniform(2.5, 5.5) if style == "miner" else rng.uniform(0.8, 3.0)),
    }


def _beta(rng: np.random.Generator, a: float, b: float) -> float:
    return float(rng.beta(a, b))


def _legit_window(rng: np.random.Generator, act: str, t: dict[str, float]) -> np.ndarray:
    v = F.DEFAULTS.copy()

    def put(name: str, value: float) -> None:
        v[IDX[name]] = value

    laggy = t["laggy"] > 0
    active = 30.0 if rng.random() > 0.05 else float(rng.uniform(3, 30))
    focus = {"combat": rng.uniform(0.85, 1.0), "gui": rng.uniform(0.5, 0.9), "idle": 0.0}.get(act, rng.uniform(0.05, 0.4))
    rate = 2 + 18 * focus
    put("active_seconds", active)
    put("move_count", float(rng.poisson(rate * active * (0.3 if act == "idle" else 1.0)) + 1))
    put("focus_share", focus)
    put("server_tick_ms_max", 50 + float(rng.exponential(3)) + (float(rng.uniform(50, 300)) if rng.random() < 0.04 else 0))
    put("server_stall_ms", float(rng.uniform(400, 3000)) if rng.random() < 0.03 else 0.0)
    put("env_special_share", _beta(rng, 1, 6) if act == "roam" else _beta(rng, 0.5, 20))

    # Latency (every activity)
    ping = t["ping"] * float(rng.uniform(0.9, 1.15))
    put("ping_median_ms", ping)
    put("ping_jitter_ms", ping * float(rng.uniform(0.05, 0.5 if laggy else 0.25)))
    kap = int(rng.poisson(2.0))
    put("ka_paired_count", kap)
    if kap:
        put("ka_pong_delta_ms", float(rng.normal(5, 25 if laggy else 10)))
    gaps = int(rng.poisson(0.9 if laggy else 0.04))
    put("gap_count", gaps)
    put("gap_burst_count", int(rng.binomial(gaps, 0.5 if laggy else 0.2)))

    # Movement: timer offset, local flags, CheckStats
    put("timer_offset_slope", float(rng.normal(0, 2.0 if laggy else 0.4)))
    flag_rate = 0.03 if laggy else 0.004
    for c in ("movement.speed", "movement.fly", "movement.step", "movement.groundspoof"):
        put(F.FLAG_FEATURES[c], float(rng.poisson(flag_rate)))
    if any(v[IDX[F.FLAG_FEATURES[c]]] > 0 for c in ("movement.speed", "movement.fly")):
        put("flag_movement_severity_max", _beta(rng, 1.2, 6))
    if rng.random() < 0.9:  # a CheckStats event within the last 330 s
        put("cs_movement_candidate_rate", float(rng.exponential(1.5 if laggy else 0.4)))
        if v[IDX["cs_movement_candidate_rate"]] > 0.05:
            put("cs_movement_discard_share", _beta(rng, 6, 2))
        put("cs_speed_max_stat", float(rng.normal(0.02 if laggy else -0.03, 0.03 if laggy else 0.015)))
        put("cs_fly_max_stat", float(rng.normal(0.0 if laggy else -0.01, 0.02 if laggy else 0.008)))

    # Idle rotations (whenever full-rate samples exist outside combat)
    idle_pairs = int(rng.poisson(rate * active * (0.25 if act == "combat" else 0.6)) if focus > 0 else 0)
    put("rot_idle_count", idle_pairs)
    if idle_pairs >= 10:
        ym = t["yaw_speed"] * float(rng.uniform(0.2, 0.6))
        put("rot_idle_yaw_mean", ym)
        put("rot_idle_yaw_sd", ym * float(rng.uniform(0.8, 1.6)))
        pm = ym * float(rng.uniform(0.15, 0.4))
        put("rot_idle_pitch_mean", pm)
        put("rot_idle_pitch_sd", pm * float(rng.uniform(0.8, 1.6)))
    put("gcd_calibrated", t["calibrated"])
    if t["calibrated"] and idle_pairs >= 10:
        put("gcd_idle_ongrid_share", float(np.clip(rng.normal(0.975, 0.015), 0, 1)))

    if act == "combat":
        fight = float(rng.uniform(min(8.0, 0.5 * active), active))
        attacks = int(rng.poisson(fight * rng.uniform(1.3, 2.6))) + 1
        eligible = int(rng.binomial(attacks, rng.uniform(0.6, 0.95)))
        attack_ticks = attacks
        put("attack_count", attacks)
        put("attack_eligible_count", eligible)
        put("attack_target_distinct", 1 + int(rng.poisson(0.7)))
        clicks = int(rng.poisson(t["cps"] * fight * 0.8))
        put("click_count", clicks)
        n_int = int(rng.binomial(clicks, 0.9)) if clicks else 0
        put("click_interval_count", n_int)
        if clicks:
            put("click_cps_peak", t["cps"] * float(rng.uniform(1.1, 1.5)))
            put("click_doubles_share", float(np.clip(t["doubles"] + rng.normal(0, 0.02), 0, 1)))
        if n_int >= 5:
            mean_i = 20.0 / t["cps"] * float(rng.uniform(0.9, 1.1))
            put("click_interval_mean", mean_i)
            put("click_interval_sd", mean_i * float(rng.uniform(0.3, 0.6)))
            put("click_cps_mean", t["cps"] * float(rng.uniform(0.9, 1.1)))
            put("click_interval_distinct", float(rng.integers(3, 9)))
            put("click_interval_mode_share", float(rng.uniform(0.3, 0.62)))
        if n_int >= 8:
            put("click_interval_skew", float(rng.uniform(0.4, 2.2)))
            put("click_interval_kurtosis", float(rng.uniform(3.0, 9.0)))
            put("click_pattern_share", float(rng.uniform(0.15, 0.45)))
        pairs = int(rng.poisson(fight * 20 * 0.9))
        put("rot_combat_count", pairs)
        ym = t["yaw_speed"] * float(rng.uniform(0.8, 1.3))
        put("rot_combat_yaw_mean", ym)
        put("rot_combat_yaw_sd", ym * float(rng.uniform(0.8, 1.4)))
        put("rot_combat_pitch_mean", ym * float(rng.uniform(0.15, 0.35)))
        put("rot_combat_pitch_sd", ym * float(rng.uniform(0.15, 0.4)))
        put("rot_combat_yaw_accel_mean", ym * float(rng.uniform(0.6, 1.0)))
        if t["calibrated"]:
            put("gcd_combat_ongrid_share", float(np.clip(rng.normal(0.955, 0.025), 0, 1)))
        snaps = int(rng.poisson(0.25))
        put("snap_count", snaps)
        put("snap_share", snaps / attack_ticks)
        n_prec = int(rng.binomial(eligible, 0.4))
        if n_prec >= 3:
            put("aim_precision_mean", t["aim_err"] * float(rng.uniform(0.85, 1.15)))
            put("aim_precision_sd", t["aim_err"] * float(rng.uniform(0.4, 0.8)))
        if eligible >= 1:
            lag = (t["ping"] - 100) / 1000 if laggy else 0.0
            p50 = float(rng.normal(t["reach_mu"] + lag, 0.08))
            p95 = p50 + float(rng.uniform(0.2, 0.45)) + (float(rng.uniform(0, 0.25)) if laggy else 0.0)
            p95 = min(p95, 3.0 + (float(rng.uniform(0, 0.25)) if laggy else 0.01))
            put("reach_p50", min(p50, p95))
            put("reach_p95", p95)
            put("reach_max", p95 + float(rng.uniform(0, 0.08)))
            put("hitbox_miss_share", _beta(rng, 2.2, 9) if laggy else _beta(rng, 1, 35))
            put("noswing_share", 0.0 if rng.random() < 0.95 else 0.05)
        vel = int(rng.poisson(fight * 0.6))
        put("velocity_count", vel)
        if vel:
            put("velocity_v_taken_ratio", float(np.clip(rng.normal(1.0, 0.04), 0, 2)))
            put("velocity_vertical_ignored_share", _beta(rng, 1.6, 6) if laggy else _beta(rng, 0.6, 30))
            if rng.random() < 0.8:
                put("velocity_jump_reset_share", float(np.clip(t["jump_reset"] + rng.normal(0, 0.08), 0, 1)))
            vh = int(rng.binomial(vel, 0.7))
            put("velocity_h_count", vh)
            if vh:
                put("velocity_h_taken_ratio", float(rng.uniform(0.75, 1.05)))
                put("velocity_h_shortfall_share", _beta(rng, 1.2, 10) if laggy else _beta(rng, 0.6, 30))
        inv = int(rng.poisson(1.0))
        put("inv_click_count", inv)
    elif act == "build":
        places = int(rng.poisson(rng.uniform(15, 70))) + 1
        el = int(rng.binomial(places, rng.uniform(0.9, 1.0)))
        put("place_count", places)
        put("place_eligible_count", el)
        if el:
            put("place_face_invalid_share", 0.0 if rng.random() < 0.97 else 1.0 / el)
            put("place_ray_miss_share", _beta(rng, 1, 60))
            put("place_cursor_mismatch_share", _beta(rng, 1.5, 22))
            put("place_reach_max", float(rng.uniform(3.0, 4.7)))
            put("place_peak_per_s", t["bridge_speed"] * float(rng.uniform(0.8, 1.15)))
    elif act == "mine":
        digs = int(rng.poisson(rng.uniform(10, 60))) + 1
        put("dig_count", digs)
        put("dig_eligible_count", int(digs * rng.uniform(1.4, 2.0)))
        put("dig_ray_miss_share", _beta(rng, 1, 50))
        put("dig_peak_per_s", t["mine_speed"] * float(rng.uniform(0.8, 1.2)))
        put(F.FLAG_FEATURES["dig.speed"], float(rng.poisson(0.01)))
    elif act == "gui":
        clicks = int(rng.poisson(rng.uniform(5, 40))) + 2
        put("inv_click_count", clicks)
        put("inv_click_interval_min_ms", float(rng.uniform(55, 260)))
        put("inv_move_ticks", float(rng.poisson(0.05)))
        put("inv_rotate_ticks", float(rng.poisson(0.05)))
    return v


def _apply_cheat(rng: np.random.Generator, v: np.ndarray, arch: str, s: float, t: dict[str, float]) -> None:
    """Modify a legit window in place for archetype ``arch`` at strength ``s`` in (0, 1]."""

    def g(name: str) -> float:
        return float(v[IDX[name]])

    def put(name: str, value: float) -> None:
        v[IDX[name]] = value

    blatant = s >= 0.6
    if arch == "killaura":
        att = int(g("attack_count") * (1 + 0.5 * s))
        put("attack_count", att)
        put("attack_eligible_count", min(att, int(g("attack_eligible_count") * (1 + 0.5 * s))))
        if blatant and rng.random() < 0.6:
            put("noswing_share", float(rng.uniform(0.3, 0.9)))
            put("multi_target_ticks", float(rng.poisson(4 * s)))
            put("attack_target_distinct", g("attack_target_distinct") + float(rng.poisson(2)))
        if g("attack_eligible_count") >= 1:
            put("hitbox_miss_share", min(1.0, g("hitbox_miss_share") + s * float(rng.uniform(0.05, 0.45))))
        snaps = g("snap_count") + float(rng.poisson(9 * s))
        put("snap_count", snaps)
        put("snap_share", min(1.0, snaps / max(1.0, att)))
        if g("aim_precision_mean") >= 0:
            put("aim_precision_mean", g("aim_precision_mean") * (1 - 0.75 * s))
            put("aim_precision_sd", g("aim_precision_sd") * (1 - 0.75 * s))
        if g("rot_combat_yaw_accel_mean") >= 0:
            put("rot_combat_yaw_accel_mean", g("rot_combat_yaw_accel_mean") * (1 + 1.2 * s))
            put("rot_combat_yaw_mean", g("rot_combat_yaw_mean") * (1 + 0.6 * s))
        if g("gcd_combat_ongrid_share") >= 0:
            put("gcd_combat_ongrid_share", float(rng.uniform(0.3, 0.7) if blatant else rng.uniform(0.7, 0.9)))
    elif arch == "reach":
        if g("reach_p50") >= 0:
            d = s * float(rng.uniform(0.25, 0.75))
            put("reach_p50", g("reach_p50") + 0.8 * d)
            put("reach_p95", g("reach_p95") + d)
            put("reach_max", g("reach_max") + 1.1 * d)
    elif arch == "aimassist":
        if g("aim_precision_mean") >= 0:
            put("aim_precision_mean", g("aim_precision_mean") * (1 - 0.65 * s))
            put("aim_precision_sd", g("aim_precision_sd") * (1 - 0.65 * s))
        if g("rot_combat_yaw_accel_mean") >= 0:
            put("rot_combat_yaw_accel_mean", g("rot_combat_yaw_accel_mean") * (1 - 0.5 * s))
            put("rot_combat_yaw_sd", g("rot_combat_yaw_sd") * (1 - 0.35 * s))
        if g("gcd_combat_ongrid_share") >= 0:
            put("gcd_combat_ongrid_share", float(rng.uniform(0.45, 0.6) if blatant else rng.uniform(0.62, 0.88)))
    elif arch == "autoclicker":
        cps = float(rng.uniform(9, 15))
        fight = max(5.0, g("attack_count") / 2.0)
        clicks = int(rng.poisson(cps * fight * 0.8)) + 40
        put("click_count", clicks)
        put("click_interval_count", int(clicks * 0.95))
        put("click_cps_mean", cps)
        put("click_cps_peak", cps * float(rng.uniform(1.0, 1.1)))
        put("click_interval_mean", 20 / cps)
        put("click_doubles_share", 0.0)
        if blatant:
            put("click_interval_sd", float(rng.uniform(0.0, 0.2)))
            put("click_interval_mode_share", float(rng.uniform(0.95, 1.0)))
            put("click_interval_distinct", float(rng.integers(1, 3)))
            put("click_interval_skew", 0.0)
            put("click_interval_kurtosis", 0.0)
            put("click_pattern_share", float(rng.uniform(0.92, 1.0)))
        else:
            put("click_interval_sd", float(rng.uniform(0.3, 0.55)))
            put("click_interval_mode_share", float(rng.uniform(0.55, 0.85)))
            put("click_interval_distinct", float(rng.integers(2, 4)))
            put("click_interval_skew", float(rng.normal(0, 0.2)))
            put("click_interval_kurtosis", float(rng.uniform(1.4, 2.4)))
            put("click_pattern_share", float(rng.uniform(0.3, 0.65)))
    elif arch == "velocity":
        if g("velocity_count") > 0:
            if blatant:
                put("velocity_v_taken_ratio", float(rng.uniform(0, 0.25)))
                put("velocity_vertical_ignored_share", float(rng.uniform(0.75, 1.0)))
                put("velocity_count", max(g("velocity_count"), 4.0))
            elif rng.random() < 0.5:  # "jump reset" module: perfect jump resets
                put("velocity_jump_reset_share", float(rng.uniform(0.92, 1.0)))
            if g("velocity_h_count") > 0:
                put("velocity_h_taken_ratio", g("velocity_h_taken_ratio") * (1 - 0.8 * s))
                put("velocity_h_shortfall_share", float(rng.uniform(0.75, 1.0) if blatant else rng.uniform(0.2, 0.55)))
    elif arch == "scaffold":
        if g("place_eligible_count") > 0:
            if blatant:
                put("place_face_invalid_share", float(rng.uniform(0.05, 0.3)))
                put("place_ray_miss_share", float(rng.uniform(0.3, 0.8)))
                put("place_cursor_mismatch_share", float(rng.uniform(0.4, 0.9)))
                put("place_peak_per_s", float(rng.uniform(8, 14)))
            else:
                put("place_ray_miss_share", float(rng.uniform(0.08, 0.25)))
                put("place_cursor_mismatch_share", float(rng.uniform(0.15, 0.3)))
                put("place_peak_per_s", float(rng.uniform(6.5, 9)))
            if g("rot_idle_yaw_sd") >= 0:
                put("rot_idle_yaw_sd", g("rot_idle_yaw_sd") * (1 + 1.5 * s))
    elif arch == "nuker":
        put("dig_peak_per_s", float(rng.uniform(10, 40) if blatant else rng.uniform(5.5, 8.5)))
        put("dig_ray_miss_share", float(rng.uniform(0.4, 0.9) if blatant else rng.uniform(0.1, 0.3)))
        put("dig_count", g("dig_count") * (1 + 2 * s))
        put(F.FLAG_FEATURES["dig.speed"], float(rng.poisson(3 * s)))
    elif arch == "timer":
        r = float(rng.uniform(1.01, 1.1) if blatant else rng.uniform(1.002, 1.007))
        put("timer_offset_slope", g("timer_offset_slope") - 1000 * (r - 1))
        put("move_count", g("move_count") * r)
        if blatant:
            put(F.FLAG_FEATURES["timer.balance"], float(rng.poisson(1.2)))
    elif arch == "speed":
        if blatant:
            put(F.FLAG_FEATURES["movement.speed"], float(rng.poisson(4 * s)))
            put("flag_movement_severity_max", float(rng.uniform(0.3, 1.0)))
            if rng.random() < 0.3:
                put(F.FLAG_FEATURES["movement.noslow"], float(rng.poisson(2)))
            put("cs_speed_max_stat", float(rng.uniform(0.1, 0.5)))
            put("cs_movement_candidate_rate", float(rng.uniform(20, 200)))
        else:
            put(F.FLAG_FEATURES["movement.speed"], float(rng.poisson(0.15)))
            put("cs_speed_max_stat", float(rng.uniform(0.012, 0.06)))
            put("cs_movement_candidate_rate", float(rng.uniform(3, 15)))
        put("cs_movement_discard_share", float(rng.uniform(0.3, 0.9)))
    elif arch == "blink":
        gaps = g("gap_count") + float(rng.poisson(1 + 4 * s))
        put("gap_count", gaps)
        put("gap_burst_count", float(rng.binomial(int(gaps), 0.85)))
        if rng.random() < 0.4:  # also spoofs ping
            put("ka_paired_count", max(g("ka_paired_count"), float(rng.integers(1, 6))))
            put("ka_pong_delta_ms", float(rng.uniform(150, 500)))
    elif arch == "invmove":
        put("inv_move_ticks", float(rng.poisson(1 + 6 * s)))
        put("inv_rotate_ticks", float(rng.poisson(4 * s)))
        put("inv_click_interval_min_ms", float(rng.uniform(0, 30) if blatant else rng.uniform(20, 55)))
    else:  # pragma: no cover
        raise ValueError(arch)


def generate(cfg: SynthConfig | None = None) -> tuple[pd.DataFrame, list[dict[str, Any]], list[str], list[str]]:
    """Return (windows, label records, trusted tenant ids, erasure lines). All SYNTHETIC."""
    cfg = cfg or SynthConfig()
    rng = np.random.default_rng(cfg.seed)
    archetypes = list(ARCHETYPES)
    rows: list[np.ndarray] = []
    meta: list[dict[str, Any]] = []
    labels: list[dict[str, Any]] = []
    erased: list[str] = []
    for pi in range(cfg.players):
        player = _uuid(rng)
        tenant = UNTRUSTED_TENANT if rng.random() < cfg.untrusted_fraction else TENANTS[int(rng.integers(len(TENANTS)))]
        cheater = rng.random() < cfg.cheater_fraction
        style = str(rng.choice(LEGIT_STYLES, p=[0.4, 0.2, 0.12, 0.13, 0.15]))
        arch = archetypes[pi % len(archetypes)] if cheater else ""
        blatant = cheater and rng.random() < cfg.blatant_fraction
        strength = float(rng.uniform(0.7, 1.0) if blatant else rng.uniform(0.15, 0.45))
        p_on = float(rng.uniform(0.6, 0.95) if blatant else rng.uniform(0.75, 1.0))
        traits = _player_traits(rng, style)
        weights = np.array(STYLE_ACTIVITY_WEIGHTS[style], dtype=np.float64)
        weights /= weights.sum()
        cheat_weights = weights.copy()
        if cheater:  # while cheating, players spend more time where the cheat helps
            for a in ARCHETYPE_ACTIVITIES[arch]:
                cheat_weights[ACTIVITIES.index(a)] += 2.0 / len(ARCHETYPE_ACTIVITIES[arch])
            cheat_weights /= cheat_weights.sum()
        protocol = int(rng.choice([47, 340])) if rng.random() < cfg.non_tick_fraction else int(rng.integers(768, 775))
        server = _uuid(rng)
        t0 = EPOCH_US + int(rng.integers(0, 14 * 24 * 120)) * F.WINDOW_US
        # Session layout first, so a cheater's cheating period (and its label) can be placed on it.
        layout = []
        for _ in range(int(rng.integers(cfg.sessions[0], cfg.sessions[1] + 1))):
            n_w = int(rng.integers(cfg.windows_per_session[0], cfg.windows_per_session[1] + 1))
            layout.append((_uuid(rng), int(rng.random() < 0.03), [t0 + wi * F.WINDOW_US for wi in range(n_w)]))
            t0 += (n_w + int(rng.integers(20, 400))) * F.WINDOW_US
        all_ws = [ws for _, _, wss in layout for ws in wss]
        first_ws, last_we = all_ws[0], all_ws[-1] + F.WINDOW_US
        cheat_from, cheat_to = first_ws, last_we
        if cheater:  # cheating covers a contiguous part of the player's history (30-100 %)
            n = len(all_ws)
            k = max(1, int(round(n * rng.uniform(0.3, 1.0))))
            i0 = int(rng.integers(0, n - k + 1))
            cheat_from, cheat_to = all_ws[i0], all_ws[i0 + k - 1] + F.WINDOW_US
        for session, hot, wss in layout:
            for ws in wss:
                cheating = cheater and cheat_from <= ws < cheat_to
                w = cheat_weights if cheating else weights
                act = str(rng.choice(ACTIVITIES, p=w))
                v = _legit_window(rng, act, traits)
                if cheating and act in ARCHETYPE_ACTIVITIES[arch] and rng.random() < p_on:
                    _apply_cheat(rng, v, arch, strength, traits)
                rows.append(v)
                meta.append(
                    {
                        "tenant_id": tenant,
                        "player": player,
                        "server_id": server,
                        "session_id": session,
                        "window_start_us": ws,
                        "window_end_us": ws + F.WINDOW_US,
                        "client_protocol": protocol,
                        "tick_client": int(protocol >= F.MIN_TICK_CLIENT_PROTOCOL),
                        "hot_loaded": hot,
                        "feature_version": F.FEATURE_VERSION,
                        "worker_unix_us": ws + F.WINDOW_US + F.GRACE_US + int(rng.integers(0, 500_000)),
                        "synthetic": 1,
                    }
                )
        labels.extend(_labels_for(rng, tenant, player, cheater, arch, first_ws, last_we, cheat_from, cheat_to))
        if rng.random() < cfg.erased_fraction:
            erased.append(f"{tenant},{player}")
    X = F.sanitize(np.vstack(rows))
    windows = pd.concat([pd.DataFrame(meta), pd.DataFrame(X.astype(np.float64), columns=list(F.FEATURE_NAMES))], axis=1)
    return windows, labels, list(TENANTS), erased


def _iso(us: int) -> str:
    return datetime.fromtimestamp(us / 1e6, tz=timezone.utc).isoformat().replace("+00:00", "Z")


def _labels_for(
    rng: np.random.Generator,
    tenant: str,
    player: str,
    cheater: bool,
    arch: str,
    start: int,
    end: int,
    cheat_from: int,
    cheat_to: int,
) -> list[dict[str, Any]]:
    span = end - start

    def rec(label: str, source: str, ls: int, le: int, category: str = "") -> dict[str, Any]:
        as_iso = rng.random() < 0.5  # exercise both timestamp encodings the loader accepts
        r = {
            "id": _uuid(rng),
            "tenant_id": tenant,
            "player_uuid": player,
            "verdict_id": _uuid(rng) if source != "manual" else None,
            "label": label,
            "source": source,
            "window_start": _iso(ls) if as_iso else ls,
            "window_end": _iso(le) if as_iso else le,
            "created_at": _iso(le + 3_600_000_000),
            "synthetic": True,
        }
        if category:
            r["category"] = category
            r["synthetic_archetype"] = arch
        return r

    out = []
    if cheater:
        if rng.random() < 0.88:  # the confirmed verdict's signal window ~ the cheating period
            cspan = cheat_to - cheat_from
            ls = cheat_from + int(cspan * rng.uniform(0, 0.1))
            le = cheat_to - int(cspan * rng.uniform(0, 0.1))
            out.append(rec("cheat", "confirmed", ls, max(le, ls + 1), ARCHETYPES[arch]))
            if rng.random() < 0.03:  # a conflicting overturned label -> ambiguous windows get dropped
                out.append(rec("legit", "overturned", ls, ls + int(span * 0.2)))
    else:
        r = rng.random()
        if r < 0.45:
            ls = start + int(span * rng.uniform(0, 0.4))
            out.append(rec("legit", "overturned", ls, end))
        elif r < 0.8:
            out.append(rec("legit", "manual", start, end))
    return out


def write(out_dir: str | Path, cfg: SynthConfig | None = None) -> dict[str, Path]:
    """Write a complete SYNTHETIC demo dataset into ``out_dir`` and return the paths."""
    cfg = cfg or SynthConfig()
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    windows, labels, trusted, erased = generate(cfg)
    paths = {
        "windows": out / "SYNTHETIC_feature_windows.parquet",
        "labels": out / "SYNTHETIC_labels.ndjson",
        "trusted": out / "SYNTHETIC_trusted_tenants.txt",
        "erased": out / "SYNTHETIC_erased.txt",
        "readme": out / "README_SYNTHETIC.txt",
    }
    save_windows(windows, paths["windows"])
    write_ndjson(labels, paths["labels"])
    paths["trusted"].write_text(f"# {SYNTHETIC_NOTICE}\n" + "\n".join(trusted) + "\n", encoding="utf-8")
    paths["erased"].write_text(f"# {SYNTHETIC_NOTICE}\n" + "\n".join(erased) + ("\n" if erased else ""), encoding="utf-8")
    summary = {
        "notice": SYNTHETIC_NOTICE,
        "config": {k: (list(v) if isinstance(v, tuple) else v) for k, v in cfg.__dict__.items()},
        "windows": int(len(windows)),
        "players": int(windows["player"].nunique()),
        "labels": len(labels),
    }
    paths["readme"].write_text(SYNTHETIC_NOTICE + "\n\n" + json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    return paths
